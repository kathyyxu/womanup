export function parseLrc(lrcText) {
  const lines = [];
  for (const raw of String(lrcText || '').split('\n')) {
    const m = raw.match(/^\[(\d{1,2}):(\d{1,2}(?:\.\d+)?)\](.*)$/);
    if (!m) continue;
    const text = m[3].trim();
    if (!text) continue;
    // skip pure credit line as active lyric if too long meta - keep it
    const t = Number(m[1]) * 60 + Number(m[2]);
    lines.push({ t, text });
  }
  return lines;
}

export const THEME_LYRIC_LINES = parseLrc(THEME_LRC);

/** 根据播放进度取当前 / 上一句 / 下一句 */
export function getLyricWindow(lines, currentTime, lookAhead = 0.05) {
  if (!lines?.length) {
    return { prev: '', current: 'Woman Up 主题曲', next: '', index: -1 };
  }
  const t = Math.max(0, currentTime + lookAhead);
  let index = 0;
  for (let i = 0; i < lines.length; i += 1) {
    if (lines[i].t <= t) index = i;
    else break;
  }
  return {
    prev: index > 0 ? lines[index - 1].text : '',
    current: lines[index]?.text || 'Woman Up 主题曲',
    next: index < lines.length - 1 ? lines[index + 1].text : '',
    index,
  };
}
